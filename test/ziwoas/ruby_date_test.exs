defmodule Ziwoas.RubyDateTest do
  use ExUnit.Case, async: true

  alias Ziwoas.RubyDate

  # Expected values from Ruby 4.0's Date.iso8601 with the system date 2026-10-05
  # (it fills the forms without a year from there); nil where Ruby raises.
  @cases [
    {"2026-03-29", ~D[2026-03-29]},
    {" 2026-03-29 ", ~D[2026-03-29]},
    {"2026-03-29\n", ~D[2026-03-29]},
    {"\t2026-03-29", ~D[2026-03-29]},
    {"2026-03-29\v", ~D[2026-03-29]},
    {"20260329", ~D[2026-03-29]},
    {" 20260329 ", ~D[2026-03-29]},
    {"260329", ~D[2026-03-29]},
    {"26-03-29", ~D[2026-03-29]},
    {"99-03-29", ~D[1999-03-29]},
    {"69-01-01", ~D[1969-01-01]},
    {"68-01-01", ~D[2068-01-01]},
    {"+26-03-29", ~D[2026-03-29]},
    {"+026-03-29", ~D[0026-03-29]},
    {"02026-03-29", ~D[2026-03-29]},
    {"+2026-03-29", ~D[2026-03-29]},
    {"-0001-01-01", ~D[-0001-01-01]},
    {"2026-088", ~D[2026-03-29]},
    {"26088", ~D[2026-03-29]},
    {"2026-000", nil},
    {"2026-366", nil},
    {"2024-366", ~D[2024-12-31]},
    {"-088", ~D[2026-03-29]},
    {"2026-W13-7", ~D[2026-03-29]},
    {"2026W137", ~D[2026-03-29]},
    {"26W137", ~D[2026-03-29]},
    {"2026-W01-1", ~D[2025-12-29]},
    {"2026-W53-1", ~D[2026-12-28]},
    {"2027-W53-1", nil},
    {"2026-W13-0", nil},
    {"2026-W13-8", nil},
    {"-w13-7", ~D[2026-03-29]},
    {"-W13-7", ~D[2026-03-29]},
    {"-w137", ~D[2026-03-29]},
    {"-w-7", ~D[2026-10-11]},
    {"2026-03-29T12:00", ~D[2026-03-29]},
    {"2026-03-29T12:00:00+02:00", ~D[2026-03-29]},
    {"2026-03-29t12:00z", ~D[2026-03-29]},
    {"2026-03-29T25:00", ~D[2026-03-29]},
    {"2026-03-29T12:00:00,5", ~D[2026-03-29]},
    {"2026-03-29T12:00+0200", ~D[2026-03-29]},
    {"20260329T1200", ~D[2026-03-29]},
    {"20260329t120000z", ~D[2026-03-29]},
    {"--03-29", ~D[2026-03-29]},
    {"--0329", ~D[2026-03-29]},
    {"--03", ~D[2026-03-01]},
    {"---29", ~D[2026-10-29]},
    {"--03-29T12:00", ~D[2026-03-29]},
    {"2026-03", ~D[2026-03-01]},
    {"2026-", ~D[2026-01-01]},
    {"26-", ~D[2026-01-01]},
    {"2026--29", ~D[2026-01-29]},
    {"2026", nil},
    {"2026-3-29", nil},
    {"2026-02-30", nil},
    {"2026-13-01", nil},
    {"2026-03-29x", nil},
    {"2026-03-29 12:00", nil},
    {"2026-03-29T1200", nil},
    {"2026-03-29T12", nil},
    {"2026-03-29TZ", nil},
    {"2026-03-", nil},
    {"2026-W13", nil},
    {"2026W13", nil},
    {"2026w13-7", nil},
    {"12:00", nil},
    {"1200", nil},
    {"T12:00", nil},
    {"-", nil},
    {"--", nil},
    {"", nil},
    {"   ", nil},
    {"\uFF12\uFF10\uFF12\uFF16-03-29", nil},
    {String.duplicate("x", 129), nil},
    {"2026-03-29" <> String.duplicate(" ", 119), nil},
    {"2026-03-29" <> String.duplicate(" ", 118), ~D[2026-03-29]}
  ]

  for {{input, expected}, i} <- Enum.with_index(@cases) do
    @input input
    @expected expected
    test "#{i}: Date.iso8601(#{inspect(String.slice(input, 0, 30))})" do
      assert RubyDate.iso8601(@input, ~D[2026-10-05]) == @expected
    end
  end

  test "anything but a string is no date" do
    assert RubyDate.iso8601(nil, ~D[2026-10-05]) == nil
    assert RubyDate.iso8601(["2026-03-29"], ~D[2026-10-05]) == nil
  end
end
